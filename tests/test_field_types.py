"""組の定義のフィールドの型(#192 段階1): 「会員 とは 番号 は 数 で 名前 は 文字列 の 組」"""

import pathlib
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from suru import Interpreter, SuruError  # noqa: E402
from suru_check import check  # noqa: E402


def _run(src: str) -> list[str]:
    check(src)
    return Interpreter().run_text(src)


def _err(src: str) -> str:
    with pytest.raises(SuruError) as info:
        check(src)
    return str(info.value)


MEMBER = "会員 とは 番号 は 数 で 名前 は 文字列 で 年齢 は 数 の 組\n"


def test_フィールドの型を書いた組を作って使う():
    src = MEMBER + (
        "会員 を 紹介文にする は 文字列\n"
        "m を 紹介文にする とは （m の 名前） + 「さんは 」 + （m の 年齢 を 文字列化する） + 「歳です」\n"
        "（1 と 「花子」 と 20 の 会員） を 紹介文にする\n"
        "（名前 は 「太郎」 で 年齢 は 30 で 番号 は 2 の 会員） の 名前\n"
    )
    assert _run(src) == ["花子さんは 20歳です", "太郎"]


def test_書いた型と違う値はエラー():
    assert "「会員」の「番号」は数ですが、文字列が渡されています" in _err(MEMBER + "（「1」 と 「花子」 と 20 の 会員）\n")
    assert "「会員」の「名前」は文字列ですが、数が渡されています" in _err(
        MEMBER + "（名前 は 5 で 番号 は 1 で 年齢 は 2 の 会員）\n")
    e = _err(MEMBER + "（1 と 「花子」 と 20 の 会員） の 年齢 + 「歳」\n")
    assert "「+」の両側の型が違います(数 と 文字列)" in e


def test_フィールドの型は型の宣言にも使える():
    src = MEMBER + "数 を 新人にする は 会員\nn を 新人にする とは n と 「新人」 と 18 の 会員\n（7 を 新人にする） の 名前\n"
    assert _run(src) == ["新人"]
    # 型の引数のない型に型の引数を書くとエラー
    assert "「会員」がとる型の引数は0個です" in _err(MEMBER + "数 の 会員 を 名前取得する は 文字列\nm を 名前取得する とは m の 名前\n")


def test_選択肢のある型と自分自身を中に持つ型():
    src = (
        "図形 とは 半径 は 数 の 円 か 幅 は 数 で 高 は 数 の 長方形\n"
        "図形 を 面積にする は 数\n"
        "形 を 面積にする とは\n"
        "  もし 形 が\n"
        "    半径 の 円 ならば 3 * 半径 ^ 2\n"
        "    幅 と 高 の 長方形 ならば 幅 * 高\n"
        "（2 の 円） を 面積にする\n"
        "（幅 は 2 で 高 は 3 の 長方形） を 面積にする\n"
    )
    assert _run(src) == ["12", "6"]
    tree = (
        "木 とは 値 は 甲 で 左 は 木 で 右 は 木 の 節 か 葉\n"
        "数 の 木 を 合計する は 数\n"
        "t を 合計する とは\n"
        "  もし t が\n"
        "    値 と 左 と 右 の 節 ならば 値 + （左 を 合計する） + （右 を 合計する）\n"
        "    葉 ならば 0\n"
        "（1 と 葉 と （2 と 葉 と 葉 の 節） の 節） を 合計する\n"
        "（「a」 と 葉 と 葉 の 節） の 値\n"
    )
    assert _run(tree) == ["3", "a"]
    assert "数" in _err(tree + "（1 と 葉 と （「b」 と 葉 と 葉 の 節） の 節）\n")


def test_甲を使う型は型の引数をとる():
    src = (
        "箱 とは 中身 は 甲 の リスト で 名札 は 文字列 の 組\n"
        "数 の 箱 を 総数にする は 数\n"
        "b を 総数にする とは b の 中身 の 長さ\n"
        "（中身 は （1 と 2 と 3） で 名札 は 「数」 の 箱） を 総数にする\n"
        "（（「a」 と 「b」） と 「字」 の 箱） の 名札\n"
    )
    assert _run(src) == ["3", "字"]
    assert "リストの要素の型がそろっていません" in _err(src + "（中身 は （1 と 「a」） で 名札 は 「x」 の 箱）\n")
    assert "「試する」の「を」には数 の 箱が必要ですが、文字列 の 箱が渡されています" in _err(
        src.split("数 の 箱")[0] + "数 の 箱 を 試する は 数\nb を 試する とは 1\n（中身 は （「a」 と 「b」） で 名札 は 「x」 の 箱） を 試する\n")


def test_後ろで定義する型もフィールドの型に書ける():
    src = "線 とは 始め は 点 で 終わり は 点 の 組\n点 とは 横 は 数 で 縦 は 数 の 組\n（（0 と 0 の 点） と （3 と 4 の 点） の 線） の 終わり の 横\n"
    assert _run(src) == ["3"]


def test_書き方の間違い():
    assert "型のすべてのフィールドに書くか、どれにも書かないか" in _err("点 とは 横 は 数 の 円 か 幅 と 高 の 長方形\n")
    assert "型のすべてのフィールドに書くか、どれにも書かないか" in _err("点 とは 幅 と 高 の 長方形 か 横 は 数 の 円\n")
    assert "「フィールド名 は 型」を「で」で区切って" in _err("点 とは 横 は 数 で 縦 の 組\n")
    assert "「年」という型はありません" in _err("点 とは 横 は 年 の 組\n")
    assert "フィールド名「横」が2回書かれています" in _err("点 とは 横 は 数 で 横 は 数 の 組\n")
    assert "フィールド「横」の型が形ごとに違います" in _err("点 とは 横 は 数 の 甲点 か 横 は 文字列 の 乙点\n")
    assert "「で」の後にフィールドを書いてください" in _err("点 とは 横 は 数 で の 組\n")


def test_書かない形は今までどおり推論する():
    assert _run("点 とは 横 と 縦 の 組\n（1 と 2 の 点） の 縦\n（「a」 と 「b」 の 点） の 横\n") == ["2", "a"]


def test_フィールドの型に数を返す動作を書ける(capsys):
    """「数 を 返す 動作」「… を 返す 入出力動作」は型の宣言と同じく「数 の 動作」と読む(#206)"""
    src = (
        "型札 とは 名 は 文字列 で 書込 は （数 を 受け取って 数 を 返す 入出力動作 を 返すこと）"
        " で 読込 は 数 を 返す 動作 の 組\n"
        "数 を 二倍表示する は 数 を 返す 入出力動作\n"
        "x を 二倍表示する とは x * 2 を 表示する\n"
        "t とは 名 は 「あ」 で 書込 は 二倍表示すること で 読込 は （1 を 表示する） の 型札\n"
        "t の 名\n"
        "21 に （t の 書込） を 適用する\n"
    )
    assert _run(src)[0] == "あ"
    assert capsys.readouterr().out == "42\n"
    # 「数 の 動作」と書いた形と同じ型なので、形ごとに書いても矛盾しない
    check("札 とは 読 は 数 を 返す 動作 の 甲札 か 読 は 数 の 動作 の 乙札\n")
