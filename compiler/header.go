package compiler

import (
	"strconv"
	"strings"
)

// ExportInfo は外部に出す関数の1つ(IR の始めの「; suru-export: 」の行から読む、#208)
type ExportInfo struct {
	Symbol string // C の名前
	Codes  string // 型の字(引数の字の後に値の字、動作なら最後に「!」。字は exportCodes)
	Name   string // する の名前
}

// Exports は IR の始めの「; suru-export: C の名前 型の字 する の名前」の行を読む
func Exports(ir string) []ExportInfo {
	var out []ExportInfo
	for _, line := range strings.Split(ir, "\n") {
		if !strings.HasPrefix(line, ";") {
			break
		}
		if !strings.HasPrefix(line, ExportMark) {
			continue
		}
		f := strings.SplitN(strings.TrimPrefix(line, ExportMark), " ", 3)
		e := ExportInfo{Symbol: f[0]}
		if len(f) == 3 {
			e.Codes, e.Name = f[1], f[2]
		}
		out = append(out, e)
	}
	return out
}

// headerTypes は型の字 → ヘッダに書く C の型と する の型
var headerTypes = map[byte][2]string{
	'l': {"int64_t", "数"}, 'i': {"int", "整数"}, 'd': {"double", "小数"}, 'f': {"float", "単精度"},
	'b': {"int", "真偽"}, 's': {"const char *", "文字列"}, 'p': {"void *", "番地"}, 'v': {"void", "無"},
}

// ExportHeader は共有ライブラリの C のヘッダ(頭の名前.h)の中身を作る(#208 段階2)。
// Python 版の export_header と同じ文字を出す
func ExportHeader(ir, prefix string) string {
	guard := strings.ToUpper(prefix) + "_H"
	var b strings.Builder
	b.WriteString("/* " + prefix + ".h: generated by suruc. Do not edit.\n" +
		" * 「する」のコンパイラが作ったヘッダです。直さないでください。\n" +
		" *\n" +
		" * Errors: a call that fails returns 0, 0.0 or NULL, and " + prefix + "_last_error()\n" +
		" *   returns its message (NULL when the last call on this thread succeeded).\n" +
		" * Strings: string arguments are UTF-8 and are copied. A returned char * is\n" +
		" *   yours: free it with " + prefix + "_free().\n" +
		" * Numbers: 数 (int64_t) must be within +-2^62; larger values are an error.\n * Threads: any thread may call these functions, also at the same time.\n" +
		" *\n" +
		" * エラー: 失敗した呼び出しは 0・0.0・NULL を返し、" + prefix + "_last_error() で文を読めます\n" +
		" *   (このスレッドの最後の呼び出しがうまくいったときは NULL)。\n" +
		" * 文字列: 引数の文字列は UTF-8 で、写し取ります。返った char * は呼んだ側のもので、\n" +
		" *   " + prefix + "_free() で解放します。\n" +
		" * 数: 数(int64_t)は ±2^62 までです。超えるとエラーになります。\n * スレッド: どのスレッドからも、同時にでも呼べます。\n" +
		" */\n" +
		"#ifndef " + guard + "\n#define " + guard + "\n\n#include <stdint.h>\n\n" +
		"#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n" +
		"/* Initializes the library (the first call also does it). 0 on success, -1 on failure.\n" +
		" * ライブラリを用意します(最初の呼び出しでも行います)。うまくいけば 0、失敗なら -1。 */\n" +
		"int " + prefix + "_init(void);\n\n" +
		"/* The error message of the last call on this thread, or NULL. The library owns it;\n * it stays valid until the next call on this thread (do not free it).\n" +
		" * このスレッドで最後に呼んだ関数のエラーの文(なければ NULL)。ライブラリのもので、\n * このスレッドで次に呼ぶまで使えます(解放しません)。 */\n" +
		"const char *" + prefix + "_last_error(void);\n\n" +
		"/* Frees a string returned by this library.\n" +
		" * このライブラリが返した文字列を解放します。 */\n" +
		"void " + prefix + "_free(void *p);\n")
	for _, e := range Exports(ir) {
		codes := strings.TrimSuffix(e.Codes, "!")
		action := codes != e.Codes
		if codes == "" {
			continue
		}
		params := codes[:len(codes)-1]
		var cps, sps []string
		for k := 0; k < len(params); k++ {
			t := headerTypes[params[k]]
			sep := " "
			if strings.HasSuffix(t[0], "*") {
				sep = ""
			}
			cps = append(cps, t[0]+sep+"a"+strconv.Itoa(k+1))
			sps = append(sps, t[1])
		}
		res := headerTypes[codes[len(codes)-1]]
		cres := res[0]
		if res[1] == "文字列" {
			cres = "char *"
		}
		args := strings.Join(cps, ", ")
		if args == "" {
			args = "void"
		}
		sig := strings.Join(sps, " と ")
		if sig == "" {
			sig = "(なし)"
		}
		b.WriteString("\n/* する: " + e.Name + "  " + sig + " → " + res[1])
		if action {
			b.WriteString("(入出力動作)")
		}
		if res[1] == "文字列" {
			b.WriteString("\n * The result is yours: free it with " + prefix + "_free(). / 値は " + prefix + "_free() で解放します。")
		}
		b.WriteString(" */\n")
		sp := " "
		if strings.HasSuffix(cres, "*") {
			sp = ""
		}
		b.WriteString(cres + sp + e.Symbol + "(" + args + ");\n")
	}
	b.WriteString("\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* " + guard + " */\n")
	return b.String()
}
